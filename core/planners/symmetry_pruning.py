"""Plan with Fast Downward, pruning symmetric states with the group of the class our abstraction collapses."""

import os
import re
from dataclasses import dataclass

from core.integrations.fast_downward import Search, actions_from_plan_file, find_sas_plan, pddl_to_sas
from core.pipeline.abstraction.abstract_task import select_class
from core.utilities.config import AbstractPlanningConfig
from core.utilities.execution import planning_run
from core.utilities.outcomes import NoResourcesError, NoSymmetriesError

LABEL = "fd"
# The file the fork reads the generators from, in the directory it runs in.
GENERATORS_FILE = "search_generators.txt"

_ATOM = re.compile(r"(Atom|NegatedAtom) ([^(]+)\((.*)\)")


@dataclass(frozen=True)
class SymmetryPruning:
    """A search of the structural symmetries fork, its group generated by the permutations of one object class."""

    search: Search
    config: AbstractPlanningConfig

    def solve(self, on_update=None):
        """Search the PDDL task, reporting it like our own pipelines."""
        config = self.config

        with planning_run(LABEL, on_update) as run:
            base_dir = os.path.abspath(run.base_dir)
            # A task without a class gets no pruning, as our abstraction collapses nothing there.
            try:
                collapsed_set = select_class(config, run.metrics)
            except (NoResourcesError, NoSymmetriesError):
                collapsed_set = None
                print("No class to prune with, searching without symmetries")

            with run.metrics.measure("concrete_fd"):
                sas_path = pddl_to_sas(base_dir, config.domain_path, config.problem_path, LABEL, self.search.script)

            generators = []
            if collapsed_set is not None:
                run.metrics.set_abstraction(collapsed_set.objects, collapsed_set.object_type)
                with run.metrics.measure("symmetry_discovery"):
                    generators = class_generators(SasTask.read(sas_path), collapsed_set.objects)
                if not generators:
                    print(f"The permutations of {collapsed_set.id} are no symmetry of the SAS task, searching without")
            with open(os.path.join(base_dir, GENERATORS_FILE), "w", encoding="utf-8") as file:
                file.writelines(" ".join(map(str, generator)) + "\n" for generator in generators)

            with run.metrics.measure("fd_search"):
                lines = find_sas_plan(base_dir, sas_path, LABEL, self.search, cwd=base_dir)

            plan = None
            if lines is not None:
                plan = actions_from_plan_file(lines)
                run.metrics.set_counter("plan_length", len(plan))

        return run.plan_result(config, plan)


@dataclass(frozen=True)
class SasTask:
    """The parts of a SAS task a symmetry must preserve, with each value's fact name."""

    values: tuple[tuple[str, ...], ...]
    goal: frozenset
    operators: tuple
    axioms: tuple

    @classmethod
    def read(cls, sas_path):
        with open(sas_path, encoding="utf-8") as file:
            lines = iter(file.read().splitlines())

        values, goal, operators, axioms = [], frozenset(), [], []
        for line in lines:
            if line == "begin_variable":
                next(lines), next(lines)
                values.append(tuple(next(lines) for _ in range(int(next(lines)))))
            elif line == "begin_goal":
                goal = frozenset(_pairs(lines, int(next(lines))))
            elif line == "begin_operator":
                next(lines)
                prevail = frozenset(_pairs(lines, int(next(lines))))
                effects = frozenset(_effect(next(lines)) for _ in range(int(next(lines))))
                operators.append((prevail, effects, int(next(lines))))
            elif line == "begin_rule":
                conditions = frozenset(_pairs(lines, int(next(lines))))
                variable, pre, post = map(int, next(lines).split())
                axioms.append((conditions, frozenset({((), variable, pre, post)})))

        return cls(tuple(values), goal, tuple(operators), tuple(axioms))


def _pairs(lines, count):
    return [tuple(map(int, next(lines).split())) for _ in range(count)]


def _effect(line):
    numbers = list(map(int, line.split()))
    count = numbers[0]
    conditions = tuple(sorted(zip(numbers[1 : 2 * count + 1 : 2], numbers[2 : 2 * count + 1 : 2])))
    return (conditions, *numbers[2 * count + 1 :])


def class_generators(task, objects):
    """A transposition and a cycle of the objects, which generate their symmetric group, as the fork's permutations.

    Empty when either one fails to map the SAS task onto itself, since the
    translator's choice of variables need not respect every object symmetry.
    """
    # The translator writes object names in lowercase.
    objects = sorted(name.casefold() for name in objects)
    transposition = {objects[0]: objects[1], objects[1]: objects[0]}
    cycle = dict(zip(objects, objects[1:] + objects[:1]))
    permutations = [transposition] if len(objects) == 2 else [transposition, cycle]

    generators = []
    for renaming in permutations:
        mapping = _fact_mapping(task, renaming)
        if mapping is None or not _is_automorphism(task, *mapping):
            return []
        generators.append(_fork_permutation(task, *mapping))
    return generators


def _fact_mapping(task, renaming):
    """The variable and value images the renaming induces, or None when it does not map variables onto variables."""
    fact_of_name = {
        name: (variable, value) for variable, names in enumerate(task.values) for value, name in enumerate(names)
    }

    variable_image, value_image = [], []
    for variable, names in enumerate(task.values):
        named = [fact_of_name.get(_rename(name, renaming)) for name in names if name != "<none of those>"]
        if None in named or len({image for image, _value in named}) != 1:
            return None
        image = named[0][0]
        if len(task.values[image]) != len(names) or ("<none of those>" in task.values[image]) != (
            "<none of those>" in names
        ):
            return None
        variable_image.append(image)
        # A variable's leftover value has no name, so it maps to the leftover value of the image.
        images = iter(named)
        value_image.append(
            [task.values[image].index(name) if name == "<none of those>" else next(images)[1] for name in names]
        )

    if sorted(variable_image) != list(range(len(task.values))):
        return None
    return variable_image, value_image


def _rename(name, renaming):
    match = _ATOM.fullmatch(name)
    if match is None:
        return name
    kind, predicate, arguments = match.groups()
    renamed = ", ".join(renaming.get(argument, argument) for argument in arguments.split(", ")) if arguments else ""
    return f"{kind} {predicate}({renamed})"


def _is_automorphism(task, variable_image, value_image):
    def fact(variable, value):
        # A precondition of -1 means none, so it stays -1.
        return variable_image[variable], value if value == -1 else value_image[variable][value]

    def facts(pairs):
        return frozenset(fact(*pair) for pair in pairs)

    def effects(effect_set):
        return frozenset(
            (tuple(sorted(fact(*pair) for pair in conditions)), *fact(variable, pre), fact(variable, post)[1])
            for conditions, variable, pre, post in effect_set
        )

    operators = {(prevail, effect_set, cost) for prevail, effect_set, cost in task.operators}
    permuted_operators = {(facts(prevail), effects(effect_set), cost) for prevail, effect_set, cost in task.operators}
    axioms = set(task.axioms)
    permuted_axioms = {(facts(conditions), effects(effect_set)) for conditions, effect_set in task.axioms}
    return facts(task.goal) == task.goal and permuted_operators == operators and permuted_axioms == axioms


def _fork_permutation(task, variable_image, value_image):
    """The images of the variables, then of every value, numbered as the fork's symmetry graph numbers them."""
    offsets, offset = [], len(task.values)
    for names in task.values:
        offsets.append(offset)
        offset += len(names)

    permutation = list(variable_image)
    for variable, images in enumerate(value_image):
        permutation.extend(offsets[variable_image[variable]] + value for value in images)
    return permutation
